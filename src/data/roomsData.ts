// Helper function to get room by slug
export const getRoomBySlug = (slug: string): Room | undefined => {
  return rooms.find((room) => room.slug === slug);
};

// Helper function to get room by ID
export const getRoomById = (id: string): Room | undefined => {
  return rooms.find((room) => room.id === id);
};

// Helper function to filter rooms by price range
export const getRoomsByPriceRange = (min: number, max: number): Room[] => {
  return rooms.filter((room) => room.price >= min && room.price <= max);
};

// Helper function to filter rooms by max guests
export const getRoomsByGuests = (guests: number): Room[] => {
  return rooms.filter((room) => room.maxGuests >= guests);
};
